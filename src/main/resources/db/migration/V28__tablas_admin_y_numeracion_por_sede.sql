-- B.4 -- El trigger asigna el consecutivo de la SEDE de la orden.
--   . El contador SOLO AVANZA: nunca se reutiliza un numero, ni aunque la orden
--     se borre despues (el borrado es logico, deleted_at).
--   . Sin sede en la orden se usa la sede por defecto, asi una instalacion de
--     una sola sede se comporta exactamente como antes.
--   . El UPSERT bloquea la fila durante el UPDATE: sin colisiones bajo
--     concurrencia, que es lo que produciria numeros repetidos.
CREATE OR REPLACE FUNCTION set_order_id_order() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER AS $fn$
DECLARE
    next_id      BIGINT;
    sede_destino BIGINT;
BEGIN
    IF NEW.id_order IS NULL THEN
        sede_destino := NEW.site_id;

        IF sede_destino IS NULL THEN
            SELECT id INTO sede_destino
            FROM sites
            WHERE tenant_id = NEW.tenant_id AND is_default
            LIMIT 1;
        END IF;

        -- Un negocio sin sede registrada -recien dado de alta- obtiene la suya
        -- automaticamente. La primera version de esta migracion lanzaba una
        -- excepcion aqui y los tests de integracion demostraron que eso DEJA SIN
        -- VENDER a cualquier negocio nuevo: el alta no crea sedes. Crear la sede
        -- por defecto es lo correcto -todo negocio tiene al menos una- y ademas
        -- garantiza que el consecutivo siempre pertenece a una sede concreta.
        IF sede_destino IS NULL THEN
            INSERT INTO sites (tenant_id, name, code, is_default)
            VALUES (NEW.tenant_id, 'Principal', 'PRINCIPAL', true)
            ON CONFLICT (tenant_id, code) DO NOTHING;

            SELECT id INTO sede_destino
            FROM sites
            WHERE tenant_id = NEW.tenant_id AND is_default
            LIMIT 1;
        END IF;

        INSERT INTO tenant_order_counters (tenant_id, site_id, last_id)
        VALUES (NEW.tenant_id, sede_destino, 1)
        ON CONFLICT (tenant_id, site_id)
        DO UPDATE SET last_id = tenant_order_counters.last_id + 1
        RETURNING last_id INTO next_id;

        NEW.id_order := next_id;
        NEW.site_id  := sede_destino;
    END IF;
    RETURN NEW;
END $fn$;

-- B.5 -- Unicidad del consecutivo POR SEDE. Dos sedes del mismo negocio pueden
-- llevar el mismo numero; lo que no puede repetirse es dentro de una sede.
ALTER TABLE orders DROP CONSTRAINT IF EXISTS uq_orders_tenant_id_order;

CREATE UNIQUE INDEX IF NOT EXISTS uq_orders_sede_consecutivo
    ON orders (tenant_id, site_id, id_order)
    WHERE deleted_at IS NULL;

-- B.6 -- Continuidad: cada sede arranca donde iba su negocio. Sin esto una sede
-- nueva empezaria en 1 y pisaria numeros ya emitidos.
INSERT INTO tenant_order_counters (tenant_id, site_id, last_id)
SELECT s.tenant_id, s.id,
       COALESCE((SELECT MAX(o.id_order) FROM orders o
                  WHERE o.tenant_id = s.tenant_id
                    AND (o.site_id = s.id OR o.site_id IS NULL)), 0)
FROM sites s
ON CONFLICT (tenant_id, site_id) DO UPDATE
   SET last_id = GREATEST(tenant_order_counters.last_id, EXCLUDED.last_id);

