--   2. Cada sede arranca donde iba su negocio, no en 1.
--   3. El consecutivo es unico por (negocio, sede) y NO se reutiliza jamas, ni
--      aunque la orden se borre: el contador solo avanza.
--   4. Todo cambio manual del contador queda registrado con quien y cuando.
