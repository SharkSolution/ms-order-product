-- B.1 -- El contador pasa a ser por (negocio, SEDE).
-- V23 ya agrego `site_id` a la tabla, pero la PK seguia siendo solo `tenant_id`:
-- en la practica habia UN contador por negocio. La fila existente ya trae su
-- site_id (V23 la anclo a la sede por defecto), asi que cambiar la PK NO pierde
-- ni reinicia ningun contador vivo.
UPDATE tenant_order_counters c
SET    site_id = s.id
FROM   sites s
WHERE  s.tenant_id = c.tenant_id AND s.is_default AND c.site_id IS NULL;

DELETE FROM tenant_order_counters WHERE site_id IS NULL;

ALTER TABLE tenant_order_counters ALTER COLUMN site_id SET NOT NULL;
ALTER TABLE tenant_order_counters DROP CONSTRAINT IF EXISTS tenant_order_counters_pkey;
ALTER TABLE tenant_order_counters ADD CONSTRAINT tenant_order_counters_pkey
    PRIMARY KEY (tenant_id, site_id);

-- B.2 -- Prefijo fiscal visible por sede. El folio impreso pasa a ser
-- `<prefijo>-<consecutivo>`; el prefijo distingue sedes SIN tocar el
-- consecutivo, que es el dato fiscal. Vacio por defecto: una sede unica sigue
-- mostrando el numero pelado, como hoy.
ALTER TABLE sites ADD COLUMN IF NOT EXISTS invoice_prefix VARCHAR(10) NOT NULL DEFAULT '';

COMMENT ON COLUMN sites.invoice_prefix IS
    'Prefijo fiscal del folio de esta sede. Vacio = folio sin prefijo.';

