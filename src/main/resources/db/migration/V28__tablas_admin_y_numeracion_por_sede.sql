    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE %I TO app_user', t);
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS app_rw_%I ON %I', t, t);
    EXECUTE format('CREATE POLICY app_rw_%I ON %I FOR ALL TO app_user '
                   || 'USING (true) WITH CHECK (true)', t, t);
  END LOOP;
END $grants$;

